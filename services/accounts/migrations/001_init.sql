CREATE TABLE drivers (
  id           TEXT PRIMARY KEY,
  name         TEXT NOT NULL,
  car          TEXT NOT NULL DEFAULT '',
  plate        TEXT NOT NULL DEFAULT '',
  tariff       TEXT NOT NULL,
  rating_sum   INTEGER NOT NULL DEFAULT 0,
  rating_count INTEGER NOT NULL DEFAULT 0,
  trips        INTEGER NOT NULL DEFAULT 0,
  earned       BIGINT NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE drivers IS 'Driver accounts: profile, car, tariff and lifetime stats';
COMMENT ON COLUMN drivers.id IS 'Driver id generated by the driver app';
COMMENT ON COLUMN drivers.name IS 'Display name shown to passengers';
COMMENT ON COLUMN drivers.car IS 'Car make and model, e.g. Toyota Camry';
COMMENT ON COLUMN drivers.plate IS 'Licence plate, upper case';
COMMENT ON COLUMN drivers.tariff IS 'Tariff the driver serves: eco, comfort, business, cargo_s, cargo_m, cargo_l, intercity';
COMMENT ON COLUMN drivers.rating_sum IS 'Sum of stars given by passengers (1-5 per ride)';
COMMENT ON COLUMN drivers.rating_count IS 'Number of ratings; rating = rating_sum / rating_count, 5.0 when zero';
COMMENT ON COLUMN drivers.trips IS 'Completed rides and intercity trips';
COMMENT ON COLUMN drivers.earned IS 'Lifetime earnings, KZT';
COMMENT ON COLUMN drivers.created_at IS 'First registration time';
COMMENT ON COLUMN drivers.updated_at IS 'Last profile or stats change';

CREATE TABLE riders (
  id           TEXT PRIMARY KEY,
  rating_sum   INTEGER NOT NULL DEFAULT 0,
  rating_count INTEGER NOT NULL DEFAULT 0,
  trips        INTEGER NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE riders IS 'Passenger accounts: rating and ride count';
COMMENT ON COLUMN riders.id IS 'Passenger id generated by the passenger app';
COMMENT ON COLUMN riders.rating_sum IS 'Sum of stars given by drivers (1-5 per ride)';
COMMENT ON COLUMN riders.rating_count IS 'Number of ratings; rating = rating_sum / rating_count, 5.0 when zero';
COMMENT ON COLUMN riders.trips IS 'Completed rides';
COMMENT ON COLUMN riders.created_at IS 'First seen time';
COMMENT ON COLUMN riders.updated_at IS 'Last stats change';

CREATE TABLE inbox (
  event_id     UUID PRIMARY KEY,
  processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE inbox IS 'Ids of consumed domain events; makes at-least-once delivery idempotent';
COMMENT ON COLUMN inbox.event_id IS 'Event envelope id';
COMMENT ON COLUMN inbox.processed_at IS 'When the event was applied';

CREATE TABLE outbox (
  id           UUID PRIMARY KEY,
  subject      TEXT NOT NULL,
  payload      JSONB NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ
);
COMMENT ON TABLE outbox IS 'Transactional outbox: events written with the state change, published to NATS by a relay';
COMMENT ON COLUMN outbox.id IS 'Event envelope id, also the JetStream dedupe key';
COMMENT ON COLUMN outbox.subject IS 'NATS subject, equal to the event type';
COMMENT ON COLUMN outbox.payload IS 'Full event envelope';
COMMENT ON COLUMN outbox.created_at IS 'When the event was produced';
COMMENT ON COLUMN outbox.published_at IS 'When the relay published it; NULL means pending';
CREATE INDEX outbox_pending_idx ON outbox (created_at) WHERE published_at IS NULL;
